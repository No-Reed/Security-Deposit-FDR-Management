import { describe, expect, it } from 'vitest';
import { CreateInstrumentSchema, InstrumentFiltersSchema, DocumentUploadMetaSchema } from '@depositdesk/shared';

const draft = {
  institutionId: 'clh12345678901234567890123', instrumentType: 'FDR', instrumentNumber: 'DEMO-001',
  bankName: 'Synthetic Bank', bankBranch: 'Test branch', amount: '100.00', currency: 'INR',
  issueDate: '2026-01-01', maturityDate: '2027-01-01', purpose: 'Demo only',
};

describe('Database identifier and submission validation', () => {
  it('accepts the CUIDs generated by Prisma across submission, filters and document metadata', () => {
    expect(CreateInstrumentSchema.safeParse(draft).success).toBe(true);
    expect(InstrumentFiltersSchema.safeParse({ institutionId: draft.institutionId }).success).toBe(true);
    expect(DocumentUploadMetaSchema.safeParse({ instrumentId: draft.institutionId, category: 'FDR_COPY' }).success).toBe(true);
  });
  it('rejects fabricated identifiers, zero/negative amounts and reversed dates', () => {
    for (const changes of [
      { institutionId: 'demo-inst-1' }, { amount: '0' }, { amount: '-1' },
      { issueDate: '2028-01-01' },
    ]) expect(CreateInstrumentSchema.safeParse({ ...draft, ...changes }).success).toBe(false);
  });
});
